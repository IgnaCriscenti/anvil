func TestCreateTableSQL(t *testing.T) {
	users := Table{Name: "users", Columns: []Column{
		{Name: "id", Type: "integer", PK: true, AutoInc: true},
		{Name: "name", Type: "varchar(100)"},
		{Name: "email", Type: "text", Nullable: true, Default: "'x@y.z'"},
	}}
	tags := Table{Name: "tags", Columns: []Column{
		{Name: "user_id", Type: "integer", PK: true},
		{Name: "tag", Type: "text", PK: true},
	}}
	tests := []struct {
		d     drivers.Driver
		table Table
		want  string
	}{
		{drivers.Postgres{}, users, `CREATE TABLE "users" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "name" varchar(100) NOT NULL,
  "email" text DEFAULT 'x@y.z',
  PRIMARY KEY ("id")
)`},
		{drivers.MySQL{}, users, "CREATE TABLE `users` (\n  `id` integer AUTO_INCREMENT,\n  `name` varchar(100) NOT NULL,\n  `email` text DEFAULT 'x@y.z',\n  PRIMARY KEY (`id`)\n)"},
		{drivers.SQLite{}, users, `CREATE TABLE "users" (
  "id" INTEGER PRIMARY KEY AUTOINCREMENT,
  "name" varchar(100) NOT NULL,
  "email" text DEFAULT 'x@y.z'
)`},
		{drivers.SQLite{}, tags, `CREATE TABLE "tags" (
  "user_id" integer NOT NULL,
  "tag" text NOT NULL,
  PRIMARY KEY ("user_id", "tag")
)`},
	}
	for _, tt := range tests {
		got, err := CreateTable(tt.d, tt.table)
		if err != nil {
			t.Fatalf("%T: %v", tt.d, err)
		}
		if got != tt.want {
			t.Errorf("%T:\n got %s\nwant %s", tt.d, got, tt.want)
		}
	}
}

func TestCreateTableInvalid(t *testing.T) {
	col := Column{Name: "a", Type: "int"}
	tests := map[string]Table{
		"no name":           {Columns: []Column{col}},
		"no columns":        {Name: "t"},
		"column no name":    {Name: "t", Columns: []Column{{Type: "int"}}},
		"no type":           {Name: "t", Columns: []Column{{Name: "a"}}},
		"bad type":          {Name: "t", Columns: []Column{{Name: "a", Type: "int); drop table x; --"}}},
		"repeated":          {Name: "t", Columns: []Column{col, {Name: "A", Type: "text"}}},
		"autoinc not pk":    {Name: "t", Columns: []Column{{Name: "a", Type: "int", AutoInc: true}}},
		"autoinc composite": {Name: "t", Columns: []Column{{Name: "a", Type: "int", PK: true, AutoInc: true}, {Name: "b", Type: "int", PK: true}}},
		"autoinc default":   {Name: "t", Columns: []Column{{Name: "a", Type: "int", PK: true, AutoInc: true, Default: "1"}}},
		"default with ;":    {Name: "t", Columns: []Column{{Name: "a", Type: "int", Default: "1); drop table x; --"}}},
	}
	for name, tb := range tests {
		if _, err := CreateTable(drivers.Postgres{}, tb); err == nil {
			t.Errorf("%s: expected an error", name)
		}
	}
}

func TestCreateDatabaseSQL(t *testing.T) {
	if got, _ := CreateDatabase(drivers.Postgres{}, ` my"db `); got != `CREATE DATABASE "my""db"` {
		t.Errorf("pg: %s", got)
	}
	if got, _ := CreateDatabase(drivers.MySQL{}, "my`db"); got != "CREATE DATABASE `my``db`" {
		t.Errorf("mysql: %s", got)
	}
	if _, err := CreateDatabase(drivers.SQLite{}, "x"); err == nil {
		t.Error("sqlite: expected an error")
	}
	if _, err := CreateDatabase(drivers.Postgres{}, " "); err == nil {
		t.Error("empty name: expected an error")
	}
}

// TestCreateTableSQLite creates a new database file and a table in it, and
// reads the table back through the driver.
func TestCreateTableSQLite(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "new db.sqlite")
	created, err := drivers.CreateSQLiteFile(ctx, path)
	if err != nil || !created {
		t.Fatalf("CreateSQLiteFile: %v, %v", created, err)
	}
	if created, err := drivers.CreateSQLiteFile(ctx, path); err != nil || created {
		t.Fatalf("existing file: %v, %v", created, err)
	}

	d := drivers.SQLite{}
	db, err := drivers.Connect(ctx, models.DBConn{Engine: models.EngineSQLite, DB: path}, "")
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()

	stmt, err := CreateTable(d, Table{Name: "notes", Columns: []Column{
		{Name: "id", Type: "integer", PK: true, AutoInc: true},
		{Name: "body", Type: "text", Default: "''"},
		{Name: "at", Type: "timestamp", Nullable: true, Default: "CURRENT_TIMESTAMP"},
	}})
	if err != nil {
		t.Fatal(err)
	}
	if err := Exec(ctx, db, stmt, "table"); err != nil {
		t.Fatal(err)
	}
	if err := Exec(ctx, db, stmt, "table"); err == nil || !strings.Contains(err.Error(), "already exists") {
		t.Errorf("second create: %v", err)
	}

	cols, err := d.Columns(ctx, db, drivers.Table{Name: "notes"})
	if err != nil {
		t.Fatal(err)
	}
	if len(cols) != 3 || !cols[0].PK || !cols[0].AutoInc || cols[1].Nullable || !cols[2].Nullable {
		t.Errorf("columns: %+v", cols)
	}
	if _, err := db.Exec(`INSERT INTO notes DEFAULT VALUES`); err != nil {
		t.Fatal(err)
	}
	var id int
	var body string
	if err := db.QueryRow(`SELECT id, body FROM notes`).Scan(&id, &body); err != nil || id != 1 || body != "" {
		t.Errorf("row: %d %q %v", id, body, err)
	}
}
