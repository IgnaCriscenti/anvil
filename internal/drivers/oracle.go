// Oracle is Oracle Database 12c or later (OFFSET … FETCH and identity
// columns). The connection's DB is the service name; the tables shown are
// those of the session's current schema.
type Oracle struct{}

// oracleDSN builds an oracle:// URL with url.URL, which escapes the user,
// the password and the service.
func oracleDSN(c models.DBConn, password string) (string, error) {
	port := c.Port
	if port == 0 {
		port = models.DefaultPort(models.EngineOracle)
	}

	q := url.Values{}
	switch c.SSLMode {
	case "", "disable":
	case "require":
		q.Set("SSL", "true")
		q.Set("SSL VERIFY", "false")
	case "verify":
		q.Set("SSL", "true")
		q.Set("SSL VERIFY", "true")
	default:
		return "", fmt.Errorf("unknown Oracle SSL mode %q", c.SSLMode)
	}

	u := url.URL{
		Scheme:   "oracle",
		User:     url.UserPassword(c.User, password),
		Host:     net.JoinHostPort(c.Host, strconv.Itoa(port)),
		Path:     "/" + c.DB,
		RawQuery: q.Encode(),
	}
	return u.String(), nil
}

// Open opens the pool. Oracle has no read-only sessions: on read-only
// connections writes are blocked by anvil itself (SPEC §8).
func (Oracle) Open(ctx context.Context, c models.DBConn, password string) (*sql.DB, error) {
	dsn, err := oracleDSN(c, password)
	if err != nil {
		return nil, err
	}
	return sql.OpenDB(goora.NewConnector(dsn)), nil
}

// ListDatabases is empty: the service is the database.
func (Oracle) ListDatabases(context.Context, *sql.DB) ([]string, error) { return nil, nil }

func (Oracle) MaintenanceDB() string { return "" }

func (Oracle) ListTables(ctx context.Context, db *sql.DB) ([]Table, error) {
	rows, err := db.QueryContext(ctx, `
		SELECT owner, table_name, 0 FROM all_tables
		WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
		  AND nested = 'NO' AND secondary = 'N' AND table_name NOT LIKE 'BIN$%'
		UNION ALL
		SELECT owner, view_name, 1 FROM all_views
		WHERE owner = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
		ORDER BY 1, 2`)
	return scanTables(rows, err)
}

func (Oracle) Columns(ctx context.Context, db *sql.DB, t Table) ([]Column, error) {
	rows, err := db.QueryContext(ctx, `
		SELECT c.column_name, c.data_type,
		       CASE c.nullable WHEN 'Y' THEN 1 ELSE 0 END,
		       CASE c.identity_column WHEN 'YES' THEN 1 ELSE 0 END,
		       NVL(k.position, 0)
		FROM all_tab_columns c
		LEFT JOIN (
			SELECT cc.column_name, cc.position
			FROM all_constraints con
			JOIN all_cons_columns cc
			  ON cc.owner = con.owner AND cc.constraint_name = con.constraint_name
			WHERE con.constraint_type = 'P'
			  AND con.owner = NVL(:1, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')) AND con.table_name = :2
		) k ON k.column_name = c.column_name
		WHERE c.owner = NVL(:3, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')) AND c.table_name = :4
		ORDER BY c.column_id`, t.Schema, t.Name, t.Schema, t.Name)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var cols []Column
	for rows.Next() {
		var c Column
		var nullable, identity int
		if err := rows.Scan(&c.Name, &c.DBType, &nullable, &identity, &c.PKOrdinal); err != nil {
			return nil, err
		}
		c.Nullable, c.AutoInc, c.PK = nullable != 0, identity != 0, c.PKOrdinal > 0
		cols = append(cols, c)
	}
	return cols, rows.Err()
}

func (Oracle) ForeignKeys(ctx context.Context, db *sql.DB, t Table) ([]ForeignKey, error) {
	return scanForeignKeys(db.QueryContext(ctx, `
		SELECT c.constraint_name, r.owner, r.table_name, cc.column_name, rc.column_name
		FROM all_constraints c
		JOIN all_constraints r ON r.owner = c.r_owner AND r.constraint_name = c.r_constraint_name
		JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name
		JOIN all_cons_columns rc
		  ON rc.owner = r.owner AND rc.constraint_name = r.constraint_name AND rc.position = cc.position
		WHERE c.constraint_type = 'R'
		  AND c.owner = NVL(:1, SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')) AND c.table_name = :2
		ORDER BY c.constraint_name, cc.position`, t.Schema, t.Name))
}

func (Oracle) QuoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func (Oracle) Placeholder(n int) string { return ":" + strconv.Itoa(n) }

func (Oracle) SplitStatements(sql string) []Span { return oracleDialect.split(sql) }

func (Oracle) Analyze(stmt string) Statement { return oracleDialect.analyze(stmt) }

func (Oracle) AutoIncrement(typ string) (string, bool) {
	return typ + " GENERATED BY DEFAULT AS IDENTITY", false
}

func (Oracle) CreateDatabase(string) string { return "" }

func (Oracle) Limit(orderBy, limit, offset string) string {
	q := orderBy
	if offset != "" {
		q += " OFFSET " + offset + " ROWS"
	}
	return q + " FETCH NEXT " + limit + " ROWS ONLY"
}

// InsertDefaults: Oracle has no DEFAULT VALUES, so the first column takes
// DEFAULT and the rest get theirs.
func (d Oracle) InsertDefaults(table string, cols []Column) string {
	if len(cols) == 0 {
		return "INSERT INTO " + table + " VALUES (DEFAULT)"
	}
	return "INSERT INTO " + table + " (" + d.QuoteIdent(cols[0].Name) + ") VALUES (DEFAULT)"
}
